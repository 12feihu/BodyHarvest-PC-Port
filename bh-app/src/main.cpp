// XInput plumbing — wire Xbox-style controllers to BH's N64 OSContPad.
//
// Polled from stub_poll_input (called once per osContStartReadData, which
// after Phase 7's SI deferral runs at ~60 Hz). The N64-side stub_get_input
// then reads from the cached snapshot — keeps the conversion math out of
// any hot loop and matches real libultra semantics (one snapshot per
// joybus poll).
//
// N64 controller button bits (per libultra OSContPad.button):
//   0x8000 A      0x4000 B      0x2000 Z      0x1000 START
//   0x0800 D-Up   0x0400 D-Dn   0x0200 D-L    0x0100 D-R
//   0x0020 L      0x0010 R
//   0x0008 C-Up   0x0004 C-Dn   0x0002 C-L    0x0001 C-R
//
// Mapping (BH plays best with the standard N64-on-Xbox layout):
//   Xbox A          -> N64 A         (jump / confirm)
//   Xbox B          -> N64 B         (cancel / weapon swap)
//   Xbox X          -> N64 R         (alt grip; BH uses R rarely)
//   Xbox Y          -> N64 L
//   Xbox LB         -> N64 L
//   Xbox RB         -> N64 R
//   Xbox LT (>30%)  -> N64 Z         (shoot)
//   Xbox RT (>30%)  -> N64 Z         (shoot, either trigger)
//   Xbox D-Pad      -> N64 D-Pad
//   Xbox Start      -> N64 START
//   Xbox Back       -> N64 START     (no good N64 equivalent)
//   Xbox L stick    -> N64 analog stick (drive / walk)
//   Xbox R stick    -> N64 C buttons (look / aim, thresholded at >40%)
struct ControllerSnapshot {
    uint16_t buttons = 0;
    float    stick_x = 0.0f;
    float    stick_y = 0.0f;
    bool     connected = false;
};
std::atomic<bool> g_xinput_warned_missing{false};
// Lock-free per-controller snapshot: each controller has its own
// 64-bit slot, packed as { buttons:16, x_q15:16, y_q15:16, connected:1 }.
// 64-bit aligned atomic writes are atomic on x86-64, so reader sees a
// coherent snapshot without taking a lock.
std::atomic<uint64_t> g_pad_snapshots[4]{};

inline uint64_t pack_snapshot(const ControllerSnapshot& s) {
    auto qx = static_cast<int16_t>(std::clamp(s.stick_x, -1.0f, 1.0f) * 32767.0f);
    auto qy = static_cast<int16_t>(std::clamp(s.stick_y, -1.0f, 1.0f) * 32767.0f);
    return (uint64_t(s.buttons)     <<  0)
         | (uint64_t(uint16_t(qx))  << 16)
         | (uint64_t(uint16_t(qy))  << 32)
         | (uint64_t(s.connected ? 1u : 0u) << 48);
}

inline ControllerSnapshot unpack_snapshot(uint64_t v) {
    ControllerSnapshot s;
    s.buttons   = uint16_t(v & 0xFFFF);
    s.stick_x   = float(int16_t((v >> 16) & 0xFFFF)) / 32767.0f;
    s.stick_y   = float(int16_t((v >> 32) & 0xFFFF)) / 32767.0f;
    s.connected = ((v >> 48) & 1u) != 0;
    return s;
}

// Convert one XINPUT_STATE.Gamepad to our snapshot.
ControllerSnapshot translate_xinput(const XINPUT_GAMEPAD& gp) {
    ControllerSnapshot s{};
    s.connected = true;

    // ---- Face / shoulder / start buttons ----
    if (gp.wButtons & XINPUT_GAMEPAD_A)              s.buttons |= 0x8000;          // A
    if (gp.wButtons & XINPUT_GAMEPAD_B)              s.buttons |= 0x4000;          // B
    if (gp.wButtons & XINPUT_GAMEPAD_X)              s.buttons |= 0x0010;          // R (alt)
    if (gp.wButtons & XINPUT_GAMEPAD_Y)              s.buttons |= 0x0020;          // L (alt)
    if (gp.wButtons & XINPUT_GAMEPAD_LEFT_SHOULDER)  s.buttons |= 0x0020;          // L
    if (gp.wButtons & XINPUT_GAMEPAD_RIGHT_SHOULDER) s.buttons |= 0x0010;          // R
    if (gp.wButtons & XINPUT_GAMEPAD_START)          s.buttons |= 0x1000;          // START
    if (gp.wButtons & XINPUT_GAMEPAD_BACK)           s.buttons |= 0x1000;          // START (fallback)

    // Triggers (XInput trigger range 0..255) -> Z if past 30%
    constexpr uint8_t kTriggerThreshold = 256 * 30 / 100;
    if (gp.bLeftTrigger  > kTriggerThreshold) s.buttons |= 0x2000;                  // Z
    if (gp.bRightTrigger > kTriggerThreshold) s.buttons |= 0x2000;                  // Z

    // ---- D-Pad ----
    if (gp.wButtons & XINPUT_GAMEPAD_DPAD_UP)    s.buttons |= 0x0800;
    if (gp.wButtons & XINPUT_GAMEPAD_DPAD_DOWN)  s.buttons |= 0x0400;
    if (gp.wButtons & XINPUT_GAMEPAD_DPAD_LEFT)  s.buttons |= 0x0200;
    if (gp.wButtons & XINPUT_GAMEPAD_DPAD_RIGHT) s.buttons |= 0x0100;

    // ---- Left stick (analog) ----
    // XInput stick range: int16 -32768..32767. Dead-zone using the
    // documented threshold so resting controllers don't drift.
    auto apply_dz = [](int16_t v, int dz) -> float {
        int av = std::abs(int(v));
        if (av < dz) return 0.0f;
        float sign = v < 0 ? -1.0f : 1.0f;
        return sign * float(av - dz) / float(32767 - dz);
    };
    s.stick_x = apply_dz(gp.sThumbLX, XINPUT_GAMEPAD_LEFT_THUMB_DEADZONE);
    s.stick_y = apply_dz(gp.sThumbLY, XINPUT_GAMEPAD_LEFT_THUMB_DEADZONE);

    // ---- Right stick -> C buttons ----
    // Threshold at ~40% past dead-zone for a click-y feel; BH only cares
    // whether the C button is down, not how far.
    const float c_threshold = 0.4f;
    float rx = apply_dz(gp.sThumbRX, XINPUT_GAMEPAD_RIGHT_THUMB_DEADZONE);
    float ry = apply_dz(gp.sThumbRY, XINPUT_GAMEPAD_RIGHT_THUMB_DEADZONE);
    if (ry >  c_threshold) s.buttons |= 0x0008;  // C-Up
    if (ry < -c_threshold) s.buttons |= 0x0004;  // C-Down
    if (rx < -c_threshold) s.buttons |= 0x0002;  // C-Left
    if (rx >  c_threshold) s.buttons |= 0x0001;  // C-Right

    return s;
}

void stub_poll_input() {
    g_input_poll_calls.fetch_add(1, std::memory_order_relaxed);
    g_t_input_poll_ns.store(now_ns(), std::memory_order_relaxed);

    // Poll all four XInput slots. BH's max_controllers is set by osContSetCh
    // (usually 1 for single-player), but ultramodern still asks via
    // get_connected_device_info for higher slots — keep them all live.
    bool any_connected = false;
    for (int i = 0; i < 4; i++) {
        XINPUT_STATE state{};
        DWORD r = XInputGetState(DWORD(i), &state);
        if (r == ERROR_SUCCESS) {
            any_connected = true;
            g_pad_snapshots[i].store(pack_snapshot(translate_xinput(state.Gamepad)),
                                      std::memory_order_release);
        } else {
            g_pad_snapshots[i].store(0, std::memory_order_release);
        }
    }
    if (!any_connected && !g_xinput_warned_missing.exchange(true, std::memory_order_relaxed)) {
        std::fprintf(stderr,
            "[input] No XInput controllers connected. Plug in a controller "
            "(Xbox / DS4-via-DS4Windows / 8BitDo / etc.) and BH will see it "
            "without a restart.\n");
    }

    // Phase 13: cheat-keybind side-channel. Looks at player 1's current
    // buttons and, on a fresh R-trigger press, writes a 'z' into BH's
    // cheatInputBuffer (gated on isCheatingEnabled, which BH already
    // requires the player to unlock via a save slot named "ICHEAT").
    // This restores the six z-prefixed cheats (zfarewell, zwander,
    // zaward, zsnared, zfreed, zdefender) that ship with the game but
    // were locked out by the lack of a 'z' button binding. R is chosen
    // over L because L pops up the in-game objective screen, which
    // would swallow any follow-up button presses needed to type the
    // rest of the cheat name.
    uint8_t* rdram = g_recomp_rdram.load(std::memory_order_acquire);
    auto snap = unpack_snapshot(g_pad_snapshots[0].load(std::memory_order_acquire));
    bh::cheats::inject_z_if_r_pressed(rdram, snap.buttons);

    // Phase 14: F1 toggles the cheat-overlay window (always available,
    // bypasses BH's isCheatingEnabled gate). Detection lives here so
    // we share the input-poll cadence; the actual window runs on its
    // own thread started below in main().
    bh::cheats::poll_overlay_hotkey(rdram);

    // Phase 14c: noclip movement override. Runs every poll tick when
    // the menu toggle is on; no-op otherwise. Stick is player 1's
    // analog stick from the same snapshot we just read.
    bh::cheats::apply_noclip_movement(rdram, snap.stick_x, snap.stick_y);

    // Re-apply shield-wall disable each tick. BH restores the shield
    // wall source table from ROM on building entry/exit and level
    // transitions, so a one-shot patch would silently revert. The
    // function early-outs cheaply if the disable flag isn't set.
    bh::cheats::apply_disable_shields_tick(rdram);

    // Re-apply water-level override each tick. Per-level scripts
    // (Java boss arena lowers water on boss spawn, etc.) stomp the
    // global water Y; without the tick the user's slider value or
    // "drain water" cheat would get reset on state changes.
    bh::cheats::apply_water_override_tick(rdram);

    // Per-tick render-cull bypass — when on, writes D_8014FD2A to
    // BH's "render everything" sentinel so the master cull function
    // returns "render" for all entities. No-op when the toggle is off.
    bh::cheats::apply_render_cull_bypass_tick(rdram);

    // Per-tick far-plane override — extends the GPU Z-clip distance
    // by writing a scaled multiple of the BH-original far plane to
    // D_801411A4 each input poll. No-op when the slider's at 1.0x or
    // explicitly released.
    bh::cheats::apply_far_plane_override_tick(rdram);

    // Save-state I/O — when the "Save State" / "Load State" cheats
    // queue an operation, this handler performs the disk I/O here
    // at the frame boundary (between BH game ticks). Single-shot
    // per cheat fire; no-op the rest of the time.
    bh::cheats::apply_save_state_tick(rdram);

    // Phase 16: multiplayer POC tick — sends our position, drains
    // incoming packets, paints the ghost slot for the remote player.
    // No-op when the Options-tab toggle is off.
    bh::net::tick(rdram);
}

bool stub_get_input(int controller, uint16_t* buttons, float* x, float* y) {
    if (controller < 0 || controller >= 4) {
        if (buttons) *buttons = 0;
        if (x) *x = 0.0f;
        if (y) *y = 0.0f;
        return false;
    }
    auto snap = unpack_snapshot(g_pad_snapshots[controller].load(std::memory_order_acquire));
    if (buttons) *buttons = snap.buttons;
    if (x) *x = snap.stick_x;
    if (y) *y = snap.stick_y;
    return snap.connected;
}

void stub_set_rumble(int controller, bool on) {
    if (controller < 0 || controller >= 4) return;
    XINPUT_VIBRATION vib{};
    // Rumble Pak is a single-magnitude binary effect; mirror that with
    // both motors at full when on, both off when off.
    vib.wLeftMotorSpeed  = on ? 0xFFFF : 0;
    vib.wRightMotorSpeed = on ? 0xFFFF : 0;
    XInputSetState(DWORD(controller), &vib);
}

ultramodern::input::connected_device_info_t stub_get_connected_device_info(int controller) {
    if (controller < 0 || controller >= 4) {
        return { ultramodern::input::Device::None, ultramodern::input::Pak::None };
    }
    // BH calls osContInit (which calls get_connected_device_info) BEFORE
    // its first osContStartReadData, so the snapshot polled in
    // stub_poll_input hasn't been written yet on the very first probe and
    // we'd incorrectly report "no controller connected". Refresh the
    // snapshot here so the probe sees current device state. Subsequent
    // poll cycles will keep it updated.
    XINPUT_STATE state{};
    if (XInputGetState(DWORD(controller), &state) == ERROR_SUCCESS) {
        g_pad_snapshots[controller].store(pack_snapshot(translate_xinput(state.Gamepad)),
                                          std::memory_order_release);
        return { ultramodern::input::Device::Controller,
                 ultramodern::input::Pak::RumblePak };
    }
    g_pad_snapshots[controller].store(0, std::memory_order_release);
    return { ultramodern::input::Device::None, ultramodern::input::Pak::None };
}

