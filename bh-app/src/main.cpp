// gfx_callbacks.update_gfx runs on the main thread inside recomp::start's
// loop. We pump the Win32 message queue here so the window stays responsive.
// Also log a heartbeat once per ~second so we can tell whether the loop
// is still being driven (vs. the process being torn down externally).
void gfx_update_gfx(void*) {
    MSG msg;
    while (PeekMessageW(&msg, nullptr, 0, 0, PM_REMOVE)) {
        TranslateMessage(&msg);
        DispatchMessageW(&msg);
    }
    static std::atomic<uint64_t> tick{0};
    uint64_t n = tick.fetch_add(1, std::memory_order_relaxed);
    // recomp::start sleeps 1ms between calls, so n=1000 ~= 1s
    // Heartbeat ~every ~1s of wall-time (main loop runs ~64 Hz on Windows
    // without timeBeginPeriod(1)).
    if ((n % 60) == 0) {
        // Convert each "last event" timestamp to "ms ago" — easier to scan
        // than raw monotonic ns. -1 means the event has never happened.
        int64_t now = now_ns();
        auto ms_ago = [now](int64_t t) -> int64_t {
            return t == 0 ? -1 : (now - t) / 1'000'000;
        };
        std::fprintf(stderr,
            "[loop] tick=%llu  send_dl=%llu update_screen=%llu rsp_ucode=%llu  tasks{gfx=%llu aud=%llu vid=%llu njpeg=%llu hvq=%llu other=%llu}  audio_cb{setfreq=%llu queue=%llu frames_q=%llu getlen=%llu}  ms_ago{ucode_in=%lld ucode_out=%lld aud_q=%lld aud_getlen=%lld input=%lld(n=%llu)}\n",
            static_cast<unsigned long long>(n / 1000),
            static_cast<unsigned long long>(s_send_dl_count.load()),
            static_cast<unsigned long long>(s_update_screen_count.load()),
            static_cast<unsigned long long>(g_get_rsp_microcode_count.load()),
            static_cast<unsigned long long>(g_rsp_task_type_count[1].load()),  // M_GFXTASK
            static_cast<unsigned long long>(g_rsp_task_type_count[2].load()),  // M_AUDTASK
            static_cast<unsigned long long>(g_rsp_task_type_count[3].load()),  // M_VIDTASK
            static_cast<unsigned long long>(g_rsp_task_type_count[4].load()),  // M_NJPEGTASK
            static_cast<unsigned long long>(g_rsp_task_type_count[6].load()),  // M_HVQTASK
            static_cast<unsigned long long>(g_rsp_task_type_count[0].load() + g_rsp_task_type_count[5].load() + g_rsp_task_type_count[7].load() + g_rsp_task_type_count[8].load() + g_rsp_task_type_count[9].load()),
            static_cast<unsigned long long>(g_audio_setfreq_calls.load()),
            static_cast<unsigned long long>(g_audio_queue_calls.load()),
            static_cast<unsigned long long>(g_audio_frames_queued.load()),
            static_cast<unsigned long long>(g_audio_getlen_calls.load()),
            static_cast<long long>(ms_ago(g_t_ucode_in_ns.load())),
            static_cast<long long>(ms_ago(g_t_ucode_out_ns.load())),
            static_cast<long long>(ms_ago(g_t_audio_queue_ns.load())),
            static_cast<long long>(ms_ago(g_t_audio_getlen_ns.load())),
            static_cast<long long>(ms_ago(g_t_input_poll_ns.load())),
            static_cast<unsigned long long>(g_input_poll_calls.load()));
        // Phase 11 diag: only print aspMain exit-path stats when something
        // unusual happens — patched-jr exits should be 0 in a healthy run.
        // (The counters are always maintained; the heartbeat just doesn't
        // spam them when everything's fine.)
        uint32_t jr_n = g_aspmain_jr_target_count.load(std::memory_order_relaxed);
        uint64_t patched = g_aspmain_patched_jr.load(std::memory_order_relaxed);
        if (patched != 0 || jr_n != 0) {
            std::fprintf(stderr,
                "[loop]   aspMain{patched_jr=%llu natural_brk=%llu unique_jr=%u last=0x%04X}\n",
                static_cast<unsigned long long>(patched),
                static_cast<unsigned long long>(g_aspmain_natural_break.load()),
                unsigned(jr_n),
                unsigned(g_aspmain_last_jr_target.load()));
            if (jr_n > 0) {
                std::fprintf(stderr, "[loop]   aspMain_jr_targets={");
                for (uint32_t i = 0; i < jr_n; i++) {
                    std::fprintf(stderr, "%s0x%04X",
                                 i == 0 ? "" : ",",
                                 unsigned(g_aspmain_jr_targets[i].load(std::memory_order_relaxed)));
                }
                std::fprintf(stderr, "}\n");
            }
        }
    }
    // Replace tick=N with seconds elapsed by using actual time
    static auto t0 = std::chrono::steady_clock::now();
    (void)t0;
}

