int main(int argc, char** argv) {
    // Make stdout/stderr unbuffered so log lines flush immediately even when
    // the process is killed mid-bootstrap (very useful during phase 3b/3c).
    std::setvbuf(stdout, nullptr, _IONBF, 0);
    std::setvbuf(stderr, nullptr, _IONBF, 0);

    // Initialise dbghelp's symbol engine once, here, so the SEH filter can
    // resolve the faulting RIP to a function name. With /Z7 + /DEBUG the
    // .pdb sits next to the exe; SymInitialize picks it up automatically.
    SymSetOptions(SYMOPT_LOAD_LINES | SYMOPT_UNDNAME);
    SymInitialize(GetCurrentProcess(), nullptr, /*invade*/ TRUE);

    // Phase 16: parse multiplayer port args. Defaults make two
    // instances on one PC just work — first instance uses defaults
    // (listen 12345 -> send 12346), second instance launched with
    //   bh_app.exe --port 12346 --peer-port 12345
    uint16_t mp_my_port = 12345, mp_peer_port = 12346;
    for (int i = 1; i + 1 < argc; ++i) {
        if (std::strcmp(argv[i], "--port") == 0) {
            mp_my_port = uint16_t(std::atoi(argv[++i]));
        } else if (std::strcmp(argv[i], "--peer-port") == 0) {
            mp_peer_port = uint16_t(std::atoi(argv[++i]));
        }
    }
    bh::net::init(mp_my_port, mp_peer_port);

    // Phase 11: bring up XAudio2 for real audio output. We don't yet know
    // the sample rate (BH calls osAiSetFrequency later); the source voice
    // is created on the first set_frequency or first queue_samples call.
    // If initialisation fails, stub_queue_samples falls back to drop-on-
    // floor + simulated drain via wall-clock, matching pre-Phase-11
    // behaviour so the rest of the runtime still works.
    HRESULT hr_audio = CoInitializeEx(nullptr, COINIT_MULTITHREADED);
    if (SUCCEEDED(hr_audio) || hr_audio == RPC_E_CHANGED_MODE) {
        IXAudio2* raw_xaudio = nullptr;
        HRESULT hr = XAudio2Create(&raw_xaudio, 0, XAUDIO2_DEFAULT_PROCESSOR);
        if (SUCCEEDED(hr)) {
            g_audio.xaudio.Attach(raw_xaudio);
            hr = g_audio.xaudio->CreateMasteringVoice(&g_audio.mastering);
            if (FAILED(hr)) {
                std::fprintf(stderr, "[audio] CreateMasteringVoice failed: 0x%lX — falling back to silent simulator\n",
                             (long)hr);
                g_audio.xaudio.Reset();
                g_audio.failed = true;
            } else {
                std::fprintf(stderr, "[audio] XAudio2 initialised; awaiting BH's osAiSetFrequency.\n");
            }
        } else {
            std::fprintf(stderr, "[audio] XAudio2Create failed: 0x%lX — falling back to silent simulator\n",
                         (long)hr);
            g_audio.failed = true;
        }
    } else {
        std::fprintf(stderr, "[audio] CoInitializeEx failed: 0x%lX — falling back to silent simulator\n",
                     (long)hr_audio);
        g_audio.failed = true;
    }

    // Catch unhandled SEH (Windows structured exceptions like AV, divide
    // by zero, etc.) — these don't propagate through C++ try/catch or
    // std::terminate. The filter fires before WER takes over so we still
    // get a chance to log the faulting address.
    SetUnhandledExceptionFilter([](EXCEPTION_POINTERS* ep) -> LONG {
        DWORD code = ep->ExceptionRecord->ExceptionCode;
        void* pc = ep->ExceptionRecord->ExceptionAddress;
        std::fprintf(stderr, "\n[SEH] Unhandled exception 0x%08lX at %p\n",
                     code, pc);

        // Symbolise the faulting RIP. SymFromAddr writes a SYMBOL_INFO with
        // the function name + offset within it. We also try SymGetLineFromAddr64
        // for file:line if line info was emitted (it was, via /Z7).
        {
            constexpr size_t kMaxNameLen = 512;
            char buf[sizeof(SYMBOL_INFO) + kMaxNameLen];
            auto* sym = reinterpret_cast<SYMBOL_INFO*>(buf);
            sym->SizeOfStruct = sizeof(SYMBOL_INFO);
            sym->MaxNameLen = kMaxNameLen;
            DWORD64 disp = 0;
            if (SymFromAddr(GetCurrentProcess(),
                            reinterpret_cast<DWORD64>(pc), &disp, sym)) {
                std::fprintf(stderr, "[SEH]   in %s+0x%llX\n",
                             sym->Name, (unsigned long long)disp);
            }
            IMAGEHLP_LINE64 line{};
            line.SizeOfStruct = sizeof(line);
            DWORD line_disp = 0;
            if (SymGetLineFromAddr64(GetCurrentProcess(),
                                     reinterpret_cast<DWORD64>(pc),
                                     &line_disp, &line)) {
                std::fprintf(stderr, "[SEH]   at %s:%lu\n",
                             line.FileName, line.LineNumber);
            }
        }
        if (code == EXCEPTION_ACCESS_VIOLATION &&
            ep->ExceptionRecord->NumberParameters >= 2) {
            ULONG_PTR rw = ep->ExceptionRecord->ExceptionInformation[0];
            ULONG_PTR target = ep->ExceptionRecord->ExceptionInformation[1];
            std::fprintf(stderr, "[SEH]   AV %s 0x%p\n",
                         rw == 0 ? "read" :
                         rw == 1 ? "write" : "exec",
                         (void*)target);
        }
        std::fprintf(stderr, "[SEH] rip=%p rax=%p rbx=%p rcx=%p rdx=%p\n",
                     (void*)ep->ContextRecord->Rip,
                     (void*)ep->ContextRecord->Rax,
                     (void*)ep->ContextRecord->Rbx,
                     (void*)ep->ContextRecord->Rcx,
                     (void*)ep->ContextRecord->Rdx);
        std::fprintf(stderr, "[SEH] rsi=%p rdi=%p r8 =%p r9 =%p r10=%p\n",
                     (void*)ep->ContextRecord->Rsi,
                     (void*)ep->ContextRecord->Rdi,
                     (void*)ep->ContextRecord->R8,
                     (void*)ep->ContextRecord->R9,
                     (void*)ep->ContextRecord->R10);
        std::fprintf(stderr, "[SEH] r11=%p r12=%p r13=%p r14=%p r15=%p rsp=%p\n",
                     (void*)ep->ContextRecord->R11,
                     (void*)ep->ContextRecord->R12,
                     (void*)ep->ContextRecord->R13,
                     (void*)ep->ContextRecord->R14,
                     (void*)ep->ContextRecord->R15,
                     (void*)ep->ContextRecord->Rsp);
        std::fflush(stderr);
        return EXCEPTION_EXECUTE_HANDLER;  // terminate the process ourselves
    });

    // Catch unhandled exceptions from any thread (including detached game,
    // bootstrap, gfx, etc.) and dump their type + message before the
    // process dies. Without this, std::terminate exits silently.
    std::set_terminate([]() {
        std::fprintf(stderr, "\n[bh_app] TERMINATE called\n");
        try {
            if (auto e = std::current_exception()) {
                std::rethrow_exception(e);
            } else {
                std::fprintf(stderr, "[bh_app] terminate with no current exception\n");
            }
        } catch (const std::exception& e) {
            std::fprintf(stderr, "[bh_app]   type:    %s\n", typeid(e).name());
            std::fprintf(stderr, "[bh_app]   what():  %s\n", e.what());
        } catch (...) {
            std::fprintf(stderr, "[bh_app]   unknown non-std exception\n");
        }
        std::fflush(stderr);
        std::abort();
    });

    std::printf("bh_app: Body Harvest recompiled (Phase 4b)\n");
    std::fprintf(stderr, "[trace] before register_overlays\n");

    // Tell librecomp about all of Body Harvest's recompiled functions before
    // any of them have a chance to run.
    bh::register_overlays();
    std::fprintf(stderr, "[trace] after register_overlays\n");

    // Describe BH as a registered game. ROM hash is XXH3_64bits of the
    // 12 MiB baserom.us.z64 padded to a multiple of 4 bytes (computed once
    // via hash_rom.cpp). Mismatched bytes here would cause select_rom to
    // return IncorrectRom.
    recomp::GameEntry bh_entry{};
    bh_entry.rom_hash          = 0x9949AA9BC66F33CBULL;
    bh_entry.internal_name     = "BODY HARVEST";
    bh_entry.game_id           = u8"bh.n64.us";
    bh_entry.mod_game_id       = "bh";
    // BH's libultra code uses EEPROM (osEepromProbe / osEepromLongWrite /
    // osEepromLongRead — see src.us/core/1050.c). Each long write is
    // 0x1BD = 445 bytes, which fits 4kbit EEPROM (512 bytes) with room
    // to spare; no 16kbit needed. Registering as Sram here causes our
    // osEepromProbe_recomp to return 0 (no EEPROM detected), BH's
    // D_80047608 stays 0, and BH skips every subsequent EEPROM call
    // (read AND write) — i.e. saves silently never persist.
    bh_entry.save_type         = recomp::SaveType::Eep4k;
    bh_entry.is_enabled        = true;
    bh_entry.entrypoint_address = get_entrypoint_address();
    // Phase 13: use the rdram-capturing wrapper so the cheat side-channel
    // (and any future host-side hook) can reach into N64 RAM by symbol.
    bh_entry.entrypoint        = bh_recomp_entrypoint_with_rdram_capture;
    std::fprintf(stderr, "[trace] before register_game\n");
    recomp::register_game(bh_entry);
    std::fprintf(stderr, "[trace] after register_game\n");

    // Phase 14: spin up the Win32 cheats-overlay window on its own
    // thread so F1 can toggle it independently of the game thread.
    bh::cheats::start_overlay_thread();

    // librecomp needs a config dir to stash the validated ROM under and to
    // create `mods/` and `mod_config/` subdirs in. Pin it to the directory
    // the exe lives in — `current_path()` is unreliable (when launched
    // under windbg the cwd is `C:\WINDOWS\system32`, which throws "Access
    // is denied" the moment librecomp tries to mkdir under it).
    // Phase 6 should switch to a proper per-user path (SHGetKnownFolderPath
    // for FOLDERID_LocalAppData on Windows).
    wchar_t exe_path_buf[MAX_PATH] = {};
    GetModuleFileNameW(nullptr, exe_path_buf, MAX_PATH);
    std::filesystem::path config_dir =
        std::filesystem::path(exe_path_buf).parent_path() / "config";
    std::filesystem::create_directories(config_dir);
    recomp::register_config_path(config_dir);
    std::fprintf(stderr, "[trace] after register_config_path\n");

    // Build a Configuration with stub callbacks. Mandatory ones are filled,
    // optional ones are left default-constructed (nullptr fn pointers).
    recomp::Configuration cfg{};
    cfg.project_version = recomp::Version{0, 1, 0, "-phase15a"};

    cfg.rsp_callbacks.get_rsp_microcode  = stub_get_rsp_microcode;
    cfg.renderer_callbacks.create_render_context = bh::create_render_context;

    cfg.gfx_callbacks.create_gfx    = gfx_create_gfx;
    cfg.gfx_callbacks.create_window = gfx_create_window;
    cfg.gfx_callbacks.update_gfx    = gfx_update_gfx;

    cfg.error_handling_callbacks.message_box = stderr_message_box;

    cfg.audio_callbacks.queue_samples        = stub_queue_samples;
    cfg.audio_callbacks.get_frames_remaining = stub_get_frames_remaining;
    cfg.audio_callbacks.set_frequency        = stub_set_frequency;

    cfg.input_callbacks.poll_input               = stub_poll_input;
    cfg.input_callbacks.get_input                = stub_get_input;
    cfg.input_callbacks.set_rumble               = stub_set_rumble;
    cfg.input_callbacks.get_connected_device_info = stub_get_connected_device_info;

    // (Watchdog disabled while we isolate the post-Phase-4a regression.)

    // recomp::start blocks forever pumping update_gfx. We need a sidecar
    // thread to kick off the game once ultramodern is ready. The sidecar
    // sleeps briefly to let start_event_threads finish, validates the ROM
    // via select_rom (which copies it to config_path and verifies the hash),
    // and then flips game_status to Running.
    std::thread bootstrap_thread([]() {
        std::this_thread::sleep_for(std::chrono::milliseconds(250));

        const std::filesystem::path rom_path =
            R"(C:\BodyHarvestPC\body-harvest-decompilation\baserom.us.z64)";
        std::u8string game_id = u8"bh.n64.us";

        auto err = recomp::select_rom(rom_path, game_id);
        if (err != recomp::RomValidationError::Good) {
            std::fprintf(stderr, "[bh_app] select_rom failed: %d\n",
                         static_cast<int>(err));
            return;
        }
        std::fprintf(stderr, "[bh_app] ROM validated; starting game\n");
        recomp::start_game(game_id);
    });
    bootstrap_thread.detach();

    std::fprintf(stderr, "[trace] before recomp::start\n");
    // start() is supposed to never return under normal operation.
    try {
        recomp::start(cfg);
    } catch (const std::exception& e) {
        std::fprintf(stderr,
            "\n[bh_app] recomp::start threw: %s: %s\n",
            typeid(e).name(), e.what());
        std::fflush(stderr);
        return 1;
    } catch (...) {
        std::fprintf(stderr, "\n[bh_app] recomp::start threw unknown exception\n");
        std::fflush(stderr);
        return 1;
    }
    std::fprintf(stderr, "[trace] after recomp::start (unexpected)\n");

    std::printf("bh_app: recomp::start returned (unexpected for now)\n");
    return 0;
}
