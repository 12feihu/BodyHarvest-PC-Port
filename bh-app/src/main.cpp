// Phase 6 deadlock instrumentation: track wall-clock time of the most
// recent significant event so the heartbeat can report "ms since last X".
// "ucode_in" is when get_rsp_microcode was called (a task is being
// dispatched); "ucode_out" is when our wrapper returned post-aspMain.
// If ucode_in is recent but ucode_out is old → we're stuck inside aspMain.
// If both are old but VI ticks → BH game thread isn't queuing new tasks.
std::atomic<int64_t> g_t_ucode_in_ns{0};
std::atomic<int64_t> g_t_ucode_out_ns{0};
std::atomic<int64_t> g_t_audio_queue_ns{0};
std::atomic<int64_t> g_t_audio_getlen_ns{0};
std::atomic<uint64_t> g_audio_getlen_calls{0};
std::atomic<int64_t> g_t_input_poll_ns{0};
std::atomic<uint64_t> g_input_poll_calls{0};

inline int64_t now_ns() {
    return std::chrono::duration_cast<std::chrono::nanoseconds>(
               std::chrono::steady_clock::now().time_since_epoch())
        .count();
}

// ---------------------------------------------------------------------------
// RSP microcode dispatch.
// ---------------------------------------------------------------------------
// Phase 5: real aspMain (audio synthesizer) lifted from BH's ROM by
// RSPRecomp into bh-rsp/aspMain.cpp. Audio task type 2 (M_AUDTASK)
// dispatches here; everything else still falls back to the no-op so the
// game's audio thread can drain its queue without bailing.

RspExitReason noop_rsp_ucode(uint8_t* /*rdram*/, uint32_t /*ucode_addr*/) {
    return RspExitReason::Broke;
}

// Per-task-type tally so we can tell whether BH is feeding only audio
// (type 2 = M_AUDTASK), gfx (type 1 = M_GFXTASK), or other tasks.
std::atomic<uint64_t> g_rsp_task_type_count[16]{};

// Wrap aspMain so we can timestamp before-and-after. If ucode_in is fresh
// but ucode_out is stale, the heartbeat tells us aspMain is stuck.
RspExitReason aspMain_traced(uint8_t* rdram, uint32_t ucode_addr) {
    g_t_ucode_in_ns.store(now_ns(), std::memory_order_relaxed);
    RspExitReason r = aspMain(rdram, ucode_addr);
    g_t_ucode_out_ns.store(now_ns(), std::memory_order_relaxed);
    return r;
}

RspUcodeFunc* stub_get_rsp_microcode(const OSTask* task) {
    g_get_rsp_microcode_count.fetch_add(1, std::memory_order_relaxed);
    if (task) {
        uint32_t t = task->t.type;
        if (t < 16) {
            g_rsp_task_type_count[t].fetch_add(1, std::memory_order_relaxed);
        }
        // M_AUDTASK == 2 in libultra. Route to the lifted aspMain so the
        // audio engine actually produces samples instead of dropping them.
        if (t == 2) {
            return aspMain_traced;
        }
    }
    return noop_rsp_ucode;
}

