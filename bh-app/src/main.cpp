// Recompiled aspMain (audio synthesizer ucode), defined in bh-rsp/aspMain.cpp
// at translation-unit scope (no namespace) and with default C++ linkage.
// Must be declared at namespace scope here too — putting it inside the
// anonymous namespace would give it internal linkage and the link would
// resolve to "no such symbol" at link time.
extern RspExitReason aspMain(uint8_t* rdram, uint32_t ucode_addr);

// Phase 11 diag: aspMain exit-path counters. Live at file scope (NOT
// inside the anonymous namespace) so the extern "C" callbacks below can
// see them, and so the recompiled aspMain.cpp can call those callbacks.
//  - patched_jr_count = times we exited because do_indirect_jump fell
//    through to the "rspboot exit" fallback (we used to crash here)
//  - natural_break_count = times aspMain hit a real MIPS `break 0`
//    instruction, which is the "ucode finished its work cleanly" path
// If patched dominates and natural is ~0, aspMain almost never finishes
// the synthesis loop, which would explain why every sample buffer is 0.
std::atomic<uint64_t> g_aspmain_patched_jr{0};
std::atomic<uint64_t> g_aspmain_natural_break{0};
std::atomic<uint32_t> g_aspmain_last_jr_target{0};

// Track every UNIQUE jr target that exited via the patched fallback. Small
// fixed-size set (32 entries is wildly enough) with linear scan — only
// touched from the SP Task Thread, but written via atomics so the
// heartbeat reader can dump it. This lets us learn all the missing
// indirect-branch targets in ONE run instead of seeding them one-by-one.
constexpr int kMaxAspmainJrTargets = 64;
std::atomic<uint32_t> g_aspmain_jr_targets[kMaxAspmainJrTargets]{};
std::atomic<uint32_t> g_aspmain_jr_target_count{0};

extern "C" void aspmain_dbg_count_unhandled_jr(uint32_t jt) {
    g_aspmain_patched_jr.fetch_add(1, std::memory_order_relaxed);
    g_aspmain_last_jr_target.store(jt, std::memory_order_relaxed);

    // Linear-scan-and-insert. Single-threaded caller (SP Task Thread),
    // but we use atomics so the heartbeat can read concurrently.
    uint32_t n = g_aspmain_jr_target_count.load(std::memory_order_relaxed);
    for (uint32_t i = 0; i < n && i < kMaxAspmainJrTargets; i++) {
        if (g_aspmain_jr_targets[i].load(std::memory_order_relaxed) == jt) {
            return;  // already recorded
        }
    }
    if (n < kMaxAspmainJrTargets) {
        g_aspmain_jr_targets[n].store(jt, std::memory_order_relaxed);
        g_aspmain_jr_target_count.store(n + 1, std::memory_order_relaxed);
    }
}
extern "C" void aspmain_dbg_count_natural_break(void) {
    g_aspmain_natural_break.fetch_add(1, std::memory_order_relaxed);
}

